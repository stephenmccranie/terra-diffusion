package com.github.xandergos.terraindiffusionmc.client;

import com.github.xandergos.terraindiffusionmc.world.TerrainDiffusionBiomeSource;
import net.minecraft.ChatFormatting;
import net.minecraft.client.gui.components.Button;
import net.minecraft.client.gui.components.EditBox;
import net.minecraft.client.gui.components.StringWidget;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.client.gui.screens.worldselection.CreateWorldScreen;
import net.minecraft.core.Holder;
import net.minecraft.core.RegistryAccess;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.dimension.DimensionType;
import net.minecraft.world.level.dimension.LevelStem;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.WorldDimensions;

import java.util.HashMap;
import java.util.Map;

// Sets the terrain scale of the world being created. The scale lives on the overworld's generator, so the screen
// reads it from the world's dimensions and writes it back to them.
public final class WorldScaleSettingsScreen extends Screen {
    private static final String MOD_ID = "terrain-diffusion-mc";
    private static final int TEXT_FIELD_WIDTH = 80;
    private static final int TEXT_FIELD_HEIGHT = 20;
    private static final int BUTTON_WIDTH = 80;
    private static final int BUTTON_HEIGHT = 20;

    private static final int MAX_SCALE = TerrainDiffusionBiomeSource.MAX_SCALE;
    private static final Component LABEL_TEXT = Component.literal("World Scale");
    private static final Component DESCRIPTION_TEXT = Component.literal("Enter an integer value (1-" + MAX_SCALE + ")");
    private static final Component ERROR_TEXT =
            Component.literal("Scale must be an integer between 1 and " + MAX_SCALE).withStyle(ChatFormatting.RED);

    private final CreateWorldScreen createWorld;
    private EditBox scaleTextField;
    private StringWidget validationTextWidget;

    public WorldScaleSettingsScreen(CreateWorldScreen createWorld) {
        super(Component.translatable("terrain-diffusion-mc.world_settings.title"));
        this.createWorld = createWorld;
    }

    // True where the overworld of these dimensions is generated by this mod
    public static boolean hasTerrain(WorldDimensions dimensions) {
        return dimensions.get(LevelStem.OVERWORLD)
                .filter(overworld -> overworld.generator().getBiomeSource() instanceof TerrainDiffusionBiomeSource)
                .isPresent();
    }

    private static TerrainDiffusionBiomeSource terrain(WorldDimensions dimensions) {
        return (TerrainDiffusionBiomeSource) dimensions.get(LevelStem.OVERWORLD).orElseThrow().generator()
                .getBiomeSource();
    }

    @Override
    protected void init() {
        int centerX = this.width / 2;
        int centerY = this.height / 2;

        addCenteredTextWidget(this.title, centerX, 20, 0xFFFFFF);

        addCenteredTextWidget(DESCRIPTION_TEXT, centerX, centerY - 34, 0xAAAAAA);
        addCenteredTextWidget(LABEL_TEXT, centerX, centerY - 22, 0xFFFFFF);

        scaleTextField = new EditBox(this.font,
                centerX - TEXT_FIELD_WIDTH / 2, centerY - 10,
                TEXT_FIELD_WIDTH, TEXT_FIELD_HEIGHT,
                LABEL_TEXT);
        scaleTextField.setValue(String.valueOf(
                terrain(createWorld.getUiState().getSettings().selectedDimensions()).scale()));
        scaleTextField.setResponder(value -> validationTextWidget.setMessage(Component.empty()));
        this.addRenderableWidget(scaleTextField);
        this.setInitialFocus(scaleTextField);

        this.addRenderableWidget(Button.builder(Component.translatable("gui.done"), b -> onDonePressed())
                .bounds(centerX - BUTTON_WIDTH - 5, centerY + 20, BUTTON_WIDTH, BUTTON_HEIGHT)
                .build());
        this.addRenderableWidget(Button.builder(Component.translatable("gui.cancel"), b -> onClose())
                .bounds(centerX + 5, centerY + 20, BUTTON_WIDTH, BUTTON_HEIGHT)
                .build());

        validationTextWidget = new StringWidget(0, centerY + 46, this.width, 9, Component.empty(), this.font);
        this.addRenderableWidget(validationTextWidget);
    }

    // Adds a centered StringWidget at the given screen-center x and y position
    private void addCenteredTextWidget(Component text, int centerX, int y, int color) {
        int textWidth = this.font.width(text);
        MutableComponent coloredText = text.copy().withStyle(style -> style.withColor(color));
        StringWidget widget = new StringWidget(centerX - textWidth / 2, y, textWidth, 9, coloredText, this.font);
        this.addRenderableWidget(widget);
    }

    @Override
    public void onClose() {
        this.minecraft.setScreen(createWorld);
    }

    private void onDonePressed() {
        int scale;
        try {
            scale = Integer.parseInt(scaleTextField.getValue().trim());
        } catch (NumberFormatException exception) {
            scale = 0;
        }
        if (scale < 1 || scale > MAX_SCALE) {
            validationTextWidget.setMessage(ERROR_TEXT);
            return;
        }
        int chosen = scale;
        createWorld.getUiState().updateDimensions((registries, dimensions) -> withScale(registries, dimensions, chosen));
        onClose();
    }

    // The same dimensions with the overworld at another scale: its terrain at that scale, in the dimension type
    // tall enough for it
    private static WorldDimensions withScale(RegistryAccess.Frozen registries, WorldDimensions dimensions, int scale) {
        LevelStem overworld = dimensions.get(LevelStem.OVERWORLD).orElseThrow();
        NoiseBasedChunkGenerator generator = (NoiseBasedChunkGenerator) overworld.generator();
        Holder<DimensionType> type = registries.lookupOrThrow(Registries.DIMENSION_TYPE).getOrThrow(ResourceKey.create(
                Registries.DIMENSION_TYPE,
                ResourceLocation.fromNamespaceAndPath(MOD_ID, "terrain_diffusion_scale_" + scale)));
        Map<ResourceKey<LevelStem>, LevelStem> stems = new HashMap<>(dimensions.dimensions());
        stems.put(LevelStem.OVERWORLD, new LevelStem(type,
                new NoiseBasedChunkGenerator(terrain(dimensions).withScale(scale), generator.generatorSettings())));
        return new WorldDimensions(stems);
    }
}
